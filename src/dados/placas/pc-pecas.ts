const U = 19.05;

const FILEIRAS_60: readonly (readonly number[])[] = [
  [...Array<number>(13).fill(1), 2],
  [1.5, ...Array<number>(12).fill(1), 1.5],
  [1.75, ...Array<number>(11).fill(1), 2.25],
  [2.25, ...Array<number>(10).fill(1), 2.75],
  [1.25, 1.25, 1.25, 6.25, 1.25, 1.25, 1.25, 1.25],
];

const centrosTeclas = (): { x: number; y: number }[] =>
  FILEIRAS_60.flatMap((larguras, linha) => {
    let x = 0;
    return larguras.map((w) => {
      const centro = { x: x + (w * U) / 2, y: linha * U + U / 2 };
      x += w * U;
      return centro;
    });
  });

const teclado60 = (): Componente[] => {
  const centros = centrosTeclas();
  return [
    ...centros.map((p) => c('botao', p.x - 7, p.y - 7, 14, 14, 8, 'teclas', undefined, '#d6453d')),
    ...centros.map((p) => c('diodo', p.x - 1.3, p.y + 7.6, 2.6, 1.6, 1.1, 'diodos')),
  ];
};

