export type ChaveTexto = keyof typeof textos;

const categorias: Record<Categoria, Texto> = {
  microcontrolador: { pt: 'Microcontroladores', en: 'Microcontrollers' },
  computador: { pt: 'Computadores de placa única', en: 'Single-board computers' },
  pc: { pt: 'Hardware de PC', en: 'PC hardware' },
  modulo: { pt: 'Módulos', en: 'Modules' },
  circuito: { pt: 'Circuitos', en: 'Circuits' },
};

let atual: Idioma = 'pt';

export const definirIdioma = (idioma: Idioma): void => {
  atual = idioma;
  document.documentElement.lang = idioma === 'pt' ? 'pt-BR' : 'en';
};

export const idiomaAtual = (): Idioma => atual;

export const tr = (texto: Texto | string): string => (typeof texto === 'string' ? texto : texto[atual]);

export const ui = (chave: ChaveTexto, valores: Record<string, string | number> = {}): string =>
  Object.entries(valores).reduce<string>((acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)), textos[chave][atual]);

export const nomeCategoria = (c: Categoria): string => categorias[c][atual];

export const ORDEM_CATEGORIAS: readonly Categoria[] = ['microcontrolador', 'computador', 'pc', 'modulo', 'circuito'];
